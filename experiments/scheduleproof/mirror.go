type Mirror struct {
	chain      chain.Chain
	consensus  consensus.Consensus
	supervisor *vm.Supervisor
	failed     bool
	manager    *atomicManager
}

func NewMirror(path string, genesis store.Genesis) (*Mirror, error) {
	manager, err := openAtomicManager(path)
	if err != nil {
		return nil, err
	}
	ch := chain.NewChain(manager, genesis)
	if err := ch.Init(); err != nil {
		manager.Stop()
		return nil, err
	}
	cs := consensus.NewConsensus(db.NewMemDB(), ch, true) // no production event loop
	if err := cs.Init(); err != nil {
		ch.Stop()
		return nil, err
	}
	if err := cs.Start(); err != nil {
		ch.Stop()
		return nil, err
	}
	return &Mirror{chain: ch, consensus: cs, supervisor: vm.NewSupervisor(ch, cs), manager: manager}, nil
}
func (m *Mirror) Close()                     { m.consensus.Stop(); m.chain.Stop() }
func (m *Mirror) Frontier() types.HashHeight { return m.chain.GetFrontierMomentumStore().Identifier() }

// applyJSON reports durable progress even if the engine subsequently fails
// while prefetching or notifying listeners. Mirror operations are serialized
// by the caller; the counter is advanced only by a successful synchronous Add.
func (m *Mirror) applyJSON(raw []byte) (committed bool, err error) {
	before := m.manager.commitCount()
	err = m.ApplyJSON(raw)
	return m.manager.commitCount() != before, err
}

// ApplyJSON consumes one item from ledger.getDetailedMomentumsByHeight.
// Invalid or partially applied data poisons this disposable prototype. It must
// be rebuilt rather than serving schedules from possibly uncommitted state.
func (m *Mirror) ApplyJSON(raw []byte) (err error) {
	if m.failed {
		return fmt.Errorf("rebuild required after failed replay")
	}
	defer func() {
		if recovered := recover(); recovered != nil {
			err = fmt.Errorf("replay panic: %v", recovered)
		}
		if err != nil {
			m.failed = true
		}
	}()
	var item api.DetailedMomentum
	if err = json.Unmarshal(raw, &item); err != nil {
		return err
	}
	if item.Momentum == nil || item.Momentum.Momentum == nil {
		return fmt.Errorf("missing momentum")
	}
	mom := item.Momentum.Momentum
	mom.EnsureCache()
	if mom.Height != m.Frontier().Height+1 || mom.PreviousHash != m.Frontier().Hash {
		return fmt.Errorf("non-contiguous history")
	}
	if len(item.AccountBlocks) != len(mom.Content) || len(mom.Content) > chain.MaxAccountBlocksInMomentum {
		return fmt.Errorf("incomplete momentum content")
	}
	seen := make(map[types.AccountHeader]bool)
	for i, b := range item.AccountBlocks {
		h := mom.Content[i]
		if h == nil || b == nil || b.Address != h.Address || b.Identifier() != h.Identifier() || seen[*h] {
			return fmt.Errorf("invalid or duplicate momentum content")
		}
		seen[*h] = true
	}
	detail := &nom.DetailedMomentum{Momentum: mom, AccountBlocks: make([]*nom.AccountBlock, len(item.AccountBlocks))}
	for i, b := range item.AccountBlocks {
		if b == nil {
			return fmt.Errorf("missing account block")
		}
		detail.AccountBlocks[i], err = b.ToLedgerBlock()
		if err != nil {
			return err
		}
	}
	lock := m.chain.AcquireInsert("scheduleproof replay")
	defer lock.Unlock()
	for _, b := range detail.AccountBlocks {
		if b.BlockType == nom.BlockTypeContractSend {
			continue
		} // regenerated by its receive
		tx, e := m.supervisor.ApplyBlockInMomentum(b, mom.Height)
		if e != nil {
			return e
		}
		if e = m.chain.ForceAddAccountBlockTransaction(lock, tx); e != nil {
			return e
		}
	}
	tx, err := m.supervisor.ApplyMomentum(detail)
	if err != nil {
		return err
	}
	return m.chain.AddMomentumTransaction(lock, tx)
}

// Rewind affects only this prototype's private replica.
func (m *Mirror) Rewind(to types.HashHeight) error {
	if m.failed {
		return fmt.Errorf("rebuild required after failed replay")
	}
	lock := m.chain.AcquireInsert("scheduleproof replica rewind")
	defer lock.Unlock()
	if err := m.chain.RollbackTo(lock, to); err != nil {
		m.failed = true
		return err
	}
	return nil
}

type Slot struct {
	StartsAt time.Time
	Producer types.Address
	Pillar   string
}
type Schedule struct {
	Round       uint64
	Frontier    types.HashHeight
	Proof       types.HashHeight
	ProofCutoff time.Time
	Inputs      []*types.PillarDelegation
	Slots       []Slot
}

// ScheduleAt refuses rounds whose proof cutoff has not yet been crossed by the
// replayed chain. The replica must additionally be synchronized with the local
// node before any future production controller treats this result as usable.
func (m *Mirror) ScheduleAt(round uint64) (*Schedule, error) {
	if m.failed {
		return nil, fmt.Errorf("rebuild required after failed replay")
	}
	if round > uint64(math.MaxInt64/int64(time.Second)/300)-1 {
		return nil, fmt.Errorf("round outside supported time range")
	}
	ctx := consensus.NewConsensusContext(*m.chain.GetGenesisMomentum().Timestamp)
	start, _ := ctx.ToTime(round)
	cutoff := ctx.GenesisTime.Add(time.Second)
	if round >= 2 {
		_, cutoff = ctx.ToTime(round - 2)
	}
	frontier, err := m.chain.GetFrontierMomentumStore().GetFrontierMomentum()
	if err != nil {
		return nil, err
	}
	if frontier.Timestamp.Before(cutoff) {
		return nil, fmt.Errorf("proof cutoff not covered")
	}
	proof, err := m.chain.GetFrontierMomentumStore().GetMomentumBeforeTime(&cutoff)
	if err != nil {
		return nil, err
	}
	if proof == nil {
		return nil, fmt.Errorf("missing proof")
	}
	state := m.chain.GetMomentumStore(proof.Identifier())
	details, err := state.ComputePillarDelegations()
	if err != nil {
		return nil, err
	}
	inputs := types.ToPillarDelegation(details)
	if len(inputs) == 0 {
		return nil, fmt.Errorf("empty election inputs")
	}
	proofID := proof.Identifier()
	producers := consensus.NewElectionAlgorithm(ctx).SelectProducers(consensus.NewAlgorithmContext(inputs, &proofID))
	result := &Schedule{Round: round, Frontier: frontier.Identifier(), Proof: proof.Identifier(), ProofCutoff: cutoff, Inputs: inputs}
	for i, p := range producers {
		result.Slots = append(result.Slots, Slot{StartsAt: start.Add(time.Duration(i) * time.Duration(ctx.BlockTime) * time.Second), Producer: p.Producing, Pillar: p.Name})
	}
	return result, nil
}
