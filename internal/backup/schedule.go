const scheduleMarker = "# nomctl-schedule: "

// Schedule contains only the settings required for daily backups, never tokens.
// Version zero identifies a legacy cron entry with no tracked outcomes.
type Schedule struct {
	Version        int       `json:"version"`
	Enabled        bool      `json:"enabled"`
	Since          time.Time `json:"since"`
	Hour           int       `json:"hour"`
	Minute         int       `json:"minute"`
	RetentionDays  int       `json:"retention_days"`
	Directory      string    `json:"directory"`
	DataDirectory  string    `json:"data_directory"`
	Service        string    `json:"service"`
	LogFile        string    `json:"log_file"`
	MinFreeSpaceKB int64     `json:"min_free_space_kb"`
	Executable     string    `json:"executable"`
}

func newSchedule(cfg config.Config, executable, hostname string, now time.Time) Schedule {
	hour, minute := ScheduleTime(hostname, cfg.ServiceName, cfg.BackupHour)
	return Schedule{Version: 1, Enabled: true, Since: now.UTC(), Hour: hour, Minute: minute,
		RetentionDays: cfg.BackupRetentionDays, Directory: cfg.BackupDir, DataDirectory: cfg.ZnnDir,
		Service: cfg.ServiceName, LogFile: cfg.LogFile, MinFreeSpaceKB: cfg.MinFreeSpaceKB, Executable: executable}
}

// Config recovers the exact backup settings saved by setup, independent of the
// environment used to inspect or edit the schedule.
func (s Schedule) Config() config.Config {
	c := config.Default()
	c.BackupDir, c.ZnnDir, c.ServiceName, c.LogFile = s.Directory, s.DataDirectory, s.Service, s.LogFile
	c.BackupRetentionDays, c.BackupHour, c.MinFreeSpaceKB = s.RetentionDays, s.Hour, s.MinFreeSpaceKB
	c.MaxBackups, c.BackupCadenceDays, c.SkipPreflight = 30, 0, true
	return c
}

func renderSchedule(s Schedule) (string, error) {
	if s.Version != 1 || s.Since.IsZero() || s.Hour < 0 || s.Hour > 23 || s.Minute < 0 || s.Minute > 59 {
		return "", errors.New("invalid managed schedule metadata")
	}
	for _, p := range []string{s.Directory, s.DataDirectory, s.Executable} {
		if !filepath.IsAbs(p) {
			return "", fmt.Errorf("schedule path must be absolute: %q", p)
		}
	}
	command, err := cronCommand(s.Config(), s.Executable, true)
	if err != nil {
		return "", err
	}
	metadata, err := json.Marshal(s)
	if err != nil {
		return "", err
	}
	paused := ""
	if !s.Enabled {
		paused = "# Paused: "
	}
	return fmt.Sprintf("# Managed by nomctl: daily local chain backups; retention %d days.\n%s%s\nSHELL=/bin/sh\nPATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin\n%s%d %d * * * root %s\n",
		s.RetentionDays, scheduleMarker, metadata, paused, s.Minute, s.Hour, command), nil
}

// ReadSchedule returns nil when no cron file exists. Unrecognized or edited
// files are errors rather than a misleading 'not configured' result.
func ReadSchedule() (*Schedule, error) { return readSchedule(CronPath) }

func readSchedule(path string) (*Schedule, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	for _, line := range strings.Split(string(data), "\n") {
		if !strings.HasPrefix(line, scheduleMarker) {
			continue
		}
		var s Schedule
		if err := json.Unmarshal([]byte(strings.TrimPrefix(line, scheduleMarker)), &s); err != nil {
			return nil, err
		}
		expected, err := renderSchedule(s)
		if err != nil {
			return nil, err
		}
		if expected != string(data) {
			return nil, errors.New("backup cron file differs from its saved settings; review it and rerun 'nomctl backup schedule'")
		}
		return &s, nil
	}
	return readLegacySchedule(string(data))
}

// readLegacySchedule accepts only the exact shell-quoted format generated by
// older nomctl versions. It never evaluates commands or environment values.
func readLegacySchedule(data string) (*Schedule, error) {
	invalid := errors.New("unrecognized backup cron file; review it and rerun 'nomctl backup schedule'")
	lines := strings.Split(strings.TrimSuffix(data, "\n"), "\n")
	if len(lines) != 4 {
		return nil, invalid
	}
	prefix, command, ok := strings.Cut(lines[3], " root ")
	fields := strings.Fields(prefix)
	if !ok || len(fields) != 5 || strings.Join(fields[2:], " ") != "* * *" {
		return nil, invalid
	}
	minute, e1 := strconv.Atoi(fields[0])
	hour, e2 := strconv.Atoi(fields[1])
	if e1 != nil || e2 != nil || minute < 0 || minute > 59 || hour < 0 || hour > 23 {
		return nil, invalid
	}
	args, err := quotedCronArgs(strings.ReplaceAll(command, `\%`, "%"))
	if err != nil || len(args) != 18 {
		return nil, invalid
	}
	values := make([]string, 5)
	for i, key := range []string{"NOMCTL_BACKUP_DIR=", "NOMCTL_ZNN_DIR=", "NOMCTL_SERVICE_NAME=", "NOMCTL_LOG_FILE=", "NOMCTL_MIN_FREE_SPACE_KB="} {
		if !strings.HasPrefix(args[4+i], key) {
			return nil, invalid
		}
		values[i] = strings.TrimPrefix(args[4+i], key)
	}
	retention, e1 := strconv.Atoi(args[17])
	minFree, e2 := strconv.ParseInt(values[4], 10, 64)
	if e1 != nil || e2 != nil {
		return nil, invalid
	}
	s := Schedule{Enabled: true, Hour: hour, Minute: minute, RetentionDays: retention, Directory: values[0],
		DataDirectory: values[1], Service: values[2], LogFile: values[3], MinFreeSpaceKB: minFree, Executable: args[9]}
	expectedCommand, err := cronCommand(s.Config(), s.Executable, false)
	if err != nil {
		return nil, err
	}
	expected := fmt.Sprintf("# Managed by nomctl: daily local chain backups; retention %d days.\nSHELL=/bin/sh\nPATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin\n%d %d * * * root %s\n", retention, minute, hour, expectedCommand)
	if data != expected {
		return nil, invalid
	}
	return &s, nil
}

func quotedCronArgs(command string) ([]string, error) {
	var args []string
	for command != "" {
		if command[0] != '\'' {
			return nil, errors.New("expected quoted argument")
		}
		command = command[1:]
		var arg strings.Builder
		for {
			i := strings.IndexByte(command, '\'')
			if i < 0 {
				return nil, errors.New("unterminated argument")
			}
			arg.WriteString(command[:i])
			command = command[i+1:]
			if strings.HasPrefix(command, `"'"'`) {
				arg.WriteByte('\'')
				command = command[4:]
				continue
			}
			break
		}
		args = append(args, arg.String())
		if command == "" {
			break
		}
		if command[0] != ' ' {
			return nil, errors.New("unexpected shell syntax")
		}
		command = command[1:]
	}
	return args, nil
}

// ScheduleChanges modifies only explicitly selected fields.
type ScheduleChanges struct {
	Hour          *int
	RetentionDays *int
	Directory     *string
}

// EditLocalSchedule requires the caller to hold the shared operation lock.
func EditLocalSchedule(changes ScheduleChanges) error {
	return editSchedule(CronPath, changes, time.Now)
}

func editSchedule(path string, changes ScheduleChanges, now func() time.Time) error {
	s, err := requiredSchedule(path)
	if err != nil {
		return err
	}
	if changes.Hour != nil {
		s.Hour = *changes.Hour
	}
	if changes.RetentionDays != nil {
		s.RetentionDays = *changes.RetentionDays
	}
	if changes.Directory != nil {
		s.Directory = *changes.Directory
	}
	s.Version = 1
	return publishSchedule(*s, path, true, now)
}

// SetScheduleEnabled requires the caller to hold the shared operation lock.
func SetScheduleEnabled(enabled bool) error { return setScheduleEnabled(CronPath, enabled, time.Now) }

func setScheduleEnabled(path string, enabled bool, now func() time.Time) error {
	s, err := requiredSchedule(path)
	if err != nil {
		return err
	}
	newEpoch := s.Enabled != enabled || s.Version == 0
	s.Enabled, s.Version = enabled, 1
	return publishSchedule(*s, path, newEpoch, now)
}

// CheckScheduleUnchanged rejects a stale menu form, including a new setup form
// opened before another operator installed or paused a schedule. The caller
// must hold the operation lock through this check and the subsequent write.
func CheckScheduleUnchanged(expected *Schedule) error {
	return checkScheduleUnchanged(CronPath, expected)
}

func checkScheduleUnchanged(path string, expected *Schedule) error {
	current, err := readSchedule(path)
	if err != nil {
		return err
	}
	if (current == nil) != (expected == nil) || (current != nil && *current != *expected) {
		return errors.New("backup schedule changed while this form was open; reopen it to review the saved settings")
	}
	return nil
}

func requiredSchedule(path string) (*Schedule, error) {
	s, err := readSchedule(path)
	if err != nil {
		return nil, err
	}
	if s == nil {
		return nil, errors.New("no managed cron schedule; run 'nomctl backup schedule' first (also migrates older systemd timers)")
	}
	return s, nil
}

func atomicWrite(path string, data []byte, mode os.FileMode) error {
	f, err := os.CreateTemp(filepath.Dir(path), ".nomctl-backup-")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(f.Name()) }()
	_, writeErr := f.Write(data)
	err = errors.Join(writeErr, f.Chmod(mode), f.Sync(), f.Close())
	if err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}
